# What percentage of datasets are used more than once (re-used at least once)?
accs['wasReused'] = accs['reuse_count'] >= 1
accsPcts = accs.groupby('class', as_index=False).agg({'wasReused': 'mean'})
accsPcts = accsPcts.rename(columns={'wasReused': 'pctReused'})


# In[ ]:


# Figure 5 — proportion of datasets reused, with 95% Wilson CI
from scipy.stats import norm as _norm
z_ci = _norm.ppf(0.975)

n_per_class = accs.groupby('class').size()
p_per_class = accsPcts.set_index('class')['pctReused']

ci_lo, ci_hi = [], []
for cls in cls_order:
    p = p_per_class.get(cls, 0)
    n = n_per_class.get(cls, 1)
    denom = 1 + z_ci**2 / n
    centre = (p + z_ci**2 / (2*n)) / denom
    margin = z_ci * np.sqrt(p*(1-p)/n + z_ci**2/(4*n**2)) / denom
    ci_lo.append(centre - margin)
    ci_hi.append(centre + margin)

p_vals = p_per_class.reindex(cls_order).fillna(0).values
yerr_lo = p_vals - np.array(ci_lo)
yerr_hi = np.array(ci_hi) - p_vals
ns = [f'n={n_per_class.get(c, 0):,}' for c in cls_order]

fig, ax = plt.subplots(figsize=(7, 5))
bars = ax.bar(np.arange(len(cls_order)), p_vals * 100,
              yerr=[yerr_lo * 100, yerr_hi * 100],
              color=cls_colors, error_kw=dict(elinewidth=1.2, capsize=4, capthick=1.2),
              width=0.6)
for i, n in enumerate(ns):
    ax.text(i, (p_vals[i] + yerr_hi[i]) * 100 + 1.5, n,
            ha='center', va='bottom', fontsize=8, color='#444')
ax.set_xticks(np.arange(len(cls_order)))
ax.set_xticklabels(xlabs)
ax.set_xlabel('')
ax.set_ylabel('Proportion of datasets reused (%)')
ax.set_title('Proportion of datasets cited ≥1 time\n(95% Wilson CI)')
ax.set_ylim(0, max(p_vals) * 140)
plt.tight_layout()
