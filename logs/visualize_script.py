    pcts, yerr_lo, yerr_hi, ns = [], [], [], []

    for cat in cat_order16:
        grp = sub[sub['delay_cat'] == cat]
        n = len(grp)
        p = grp['was_reused'].mean() if n > 0 else 0
        denom = 1 + z16**2 / max(n, 1)
        centre = (p + z16**2 / (2*max(n,1))) / denom
        margin = (z16 * np.sqrt(p*(1-p)/max(n,1) + z16**2/(4*n**2)) / denom
                  if n > 0 else 0)
        pcts.append(p * 100)
        yerr_lo.append((centre - margin) * 100)
        yerr_hi.append((centre + margin) * 100)
        ns.append(n)

