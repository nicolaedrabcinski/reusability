mw_results = {}
for a, b in pairs:
    _, p = mannwhitneyu(groups_ri[a], groups_ri[b], alternative='two-sided')
    p_bonf = min(p * len(pairs), 1.0)
    mw_results[(a, b)] = p_bonf

def sig_label(p):
    if p < 0.001: return '***'
    if p < 0.01:  return '**'
    if p < 0.05:  return '*'
    return 'ns'

